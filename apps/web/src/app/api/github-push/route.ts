import { NextRequest, NextResponse } from 'next/server';

export const runtime = 'nodejs';

interface GitHubPushRequest {
  token: string;
  repoName: string;
  branch?: string;
  commitMessage?: string;
  files: Record<string, string>;
  createNew?: boolean;
  description?: string;
  isPrivate?: boolean;
}

async function githubFetch(url: string, token: string, method: string, body?: unknown) {
  const res = await fetch(url, {
    method,
    headers: {
      Authorization: `Bearer ${token}`,
      Accept: 'application/vnd.github+json',
      'Content-Type': 'application/json',
      'X-GitHub-Api-Version': '2022-11-28',
    },
    body: body ? JSON.stringify(body) : undefined,
  });
  return res;
}

export async function POST(req: NextRequest) {
  try {
    const body: GitHubPushRequest = await req.json();
    const {
      token,
      repoName,
      branch = 'main',
      commitMessage = 'feat: Vibe Swift generated project',
      files,
      createNew = false,
      description = 'Generated by Vibe Swift — AI Reverse-Engineering & Cloning Studio by The Swifters',
      isPrivate = true,
    } = body;

    if (!token || !repoName) {
      return NextResponse.json({ error: 'token and repoName are required' }, { status: 400 });
    }

    if (!files || Object.keys(files).length === 0) {
      return NextResponse.json({ error: 'No files provided to push' }, { status: 400 });
    }

    // 1. Get authenticated user
    const userRes = await githubFetch('https://api.github.com/user', token, 'GET');
    if (!userRes.ok) {
      const errData = await userRes.json().catch(() => ({}));
      return NextResponse.json(
        { error: `GitHub auth failed: ${(errData as { message?: string }).message || userRes.status}` },
        { status: 401 }
      );
    }
    const userData = await userRes.json() as { login: string };
    const owner = userData.login;
    const fullRepoName = repoName.includes('/') ? repoName : `${owner}/${repoName}`;
    const [repoOwner, repoSlug] = fullRepoName.split('/');

    // 2. Create repo if requested
    if (createNew) {
      const createRes = await githubFetch('https://api.github.com/user/repos', token, 'POST', {
        name: repoSlug,
        description,
        private: isPrivate,
        auto_init: false,
      });
      if (!createRes.ok && createRes.status !== 422) {
        // 422 = repo already exists, that's OK
        const errData = await createRes.json().catch(() => ({}));
        return NextResponse.json(
          { error: `Failed to create repo: ${(errData as { message?: string }).message || createRes.status}` },
          { status: 500 }
        );
      }
    }

    // 3. Get or create main branch ref
    let latestSha: string | null = null;
    const refRes = await githubFetch(
      `https://api.github.com/repos/${repoOwner}/${repoSlug}/git/ref/heads/${branch}`,
      token,
      'GET'
    );
    if (refRes.ok) {
      const refData = await refRes.json() as { object: { sha: string } };
      latestSha = refData.object.sha;
    }

    // 4. Create a git tree with all files
    const treeItems = await Promise.all(
      Object.entries(files).map(async ([path, content]) => {
        // Create blob for each file
        const blobRes = await githubFetch(
          `https://api.github.com/repos/${repoOwner}/${repoSlug}/git/blobs`,
          token,
          'POST',
          { content: Buffer.from(content).toString('base64'), encoding: 'base64' }
        );
        if (!blobRes.ok) {
          const errData = await blobRes.json().catch(() => ({}));
          throw new Error(`Failed to create blob for ${path}: ${(errData as { message?: string }).message}`);
        }
        const blobData = await blobRes.json() as { sha: string };
        return { path, mode: '100644', type: 'blob', sha: blobData.sha };
      })
    );

    // 5. Create tree
    const treeBody: { base_tree?: string; tree: unknown[] } = { tree: treeItems };
    if (latestSha) treeBody.base_tree = latestSha;

    const treeRes = await githubFetch(
      `https://api.github.com/repos/${repoOwner}/${repoSlug}/git/trees`,
      token,
      'POST',
      treeBody
    );
    if (!treeRes.ok) {
      const errData = await treeRes.json().catch(() => ({}));
      return NextResponse.json({ error: `Failed to create tree: ${(errData as { message?: string }).message}` }, { status: 500 });
    }
    const treeData = await treeRes.json() as { sha: string };

    // 6. Create commit
    const commitBody: { message: string; tree: string; parents?: string[] } = {
      message: commitMessage,
      tree: treeData.sha,
    };
    if (latestSha) commitBody.parents = [latestSha];

    const commitRes = await githubFetch(
      `https://api.github.com/repos/${repoOwner}/${repoSlug}/git/commits`,
      token,
      'POST',
      commitBody
    );
    if (!commitRes.ok) {
      const errData = await commitRes.json().catch(() => ({}));
      return NextResponse.json({ error: `Failed to create commit: ${(errData as { message?: string }).message}` }, { status: 500 });
    }
    const commitData = await commitRes.json() as { sha: string };

    // 7. Update or create branch ref
    if (latestSha) {
      // Update existing ref
      const updateRefRes = await githubFetch(
        `https://api.github.com/repos/${repoOwner}/${repoSlug}/git/refs/heads/${branch}`,
        token,
        'PATCH',
        { sha: commitData.sha, force: false }
      );
      if (!updateRefRes.ok) {
        const errData = await updateRefRes.json().catch(() => ({}));
        return NextResponse.json({ error: `Failed to update ref: ${(errData as { message?: string }).message}` }, { status: 500 });
      }
    } else {
      // Create new ref
      const createRefRes = await githubFetch(
        `https://api.github.com/repos/${repoOwner}/${repoSlug}/git/refs`,
        token,
        'POST',
        { ref: `refs/heads/${branch}`, sha: commitData.sha }
      );
      if (!createRefRes.ok) {
        const errData = await createRefRes.json().catch(() => ({}));
        return NextResponse.json({ error: `Failed to create ref: ${(errData as { message?: string }).message}` }, { status: 500 });
      }
    }

    const repoUrl = `https://github.com/${repoOwner}/${repoSlug}`;
    return NextResponse.json({
      success: true,
      repoUrl,
      commitSha: commitData.sha,
      branch,
      filesCount: Object.keys(files).length,
    });
  } catch (error: unknown) {
    const message = error instanceof Error ? error.message : 'GitHub push failed';
    console.error('[github-push] Error:', message);
    return NextResponse.json({ success: false, error: message }, { status: 500 });
  }
}
